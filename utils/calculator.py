def add(a,b):
    """ This function takes two numbers as input and returns their sum."""
    return a + b

def divide(a,b):
    """ This function takes two numbers as input and returns their division."""
    return a / b

def subtract(a,b):
    """ This function takes two numbers as input and returns their difference."""
    return a - b

def power(a,b):
    """ This function takes two numbers as input and returns the first number raised to the power of the second number."""
    return a ** b

def multiply(a,b):
    """ This function takes two numbers as input and returns their product."""
    return a * b

